/**
 * Generate app/utils/ogWordmark.ts — the "The Urban World" wordmark outlined in
 * Crimson Pro 600 with small-caps geometry (full-size leading capital + scaled
 * small caps, with baselines aligned in the path data itself).
 *
 * The OG image templates (components/OgImage/*.satori.vue) render this as a
 * vector <path>, which sidesteps Satori's lack of `font-variant: small-caps`
 * and its unreliable cross-size baseline alignment.
 *
 * Run:  node scripts/gen-og-wordmark.cjs   (or: pnpm gen:og-wordmark)
 * Requires the devDependency `opentype.js`. Downloads the font from Google
 * Fonts; bump FONT_URL if the version hash 404s.
 */
const fs = require('fs')
const path = require('path')
const opentype = require('opentype.js')

// Crimson Pro 600 (semibold), static TTF instance from Google Fonts.
const FONT_URL = 'https://fonts.gstatic.com/s/crimsonpro/v28/q5uUsoa5M_tv7IihmnkabC5XiXCAlXGks1WZEGpMP5s7.ttf'
const OUT = path.join(__dirname, '..', 'app', 'utils', 'ogWordmark.ts')

const TEXT = 'The Urban World'
const FULL = 100 // em size for the leading capital of each word
const SMALL = 73 // em size for the small caps (rest of each word)
const TRACK = 0.012 // letter tracking (em) — roughly matches the header's 0.01em
const BASE = 100 // shared baseline so all runs align exactly

async function main() {
  const res = await fetch(FONT_URL)
  if (!res.ok) throw new Error(`font download failed: ${res.status} ${FONT_URL}`)
  const buf = Buffer.from(await res.arrayBuffer())
  const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength))

  const out = new opentype.Path()
  let x = 0
  const drawRun = (str, size) => {
    for (const ch of str) {
      out.extend(font.getPath(ch, x, BASE, size))
      x += font.getAdvanceWidth(ch, size) + size * TRACK
    }
  }

  const words = TEXT.split(' ')
  words.forEach((word, i) => {
    drawRun(word[0], FULL) // leading capital
    drawRun(word.slice(1).toUpperCase(), SMALL) // remainder as small caps
    if (i < words.length - 1) x += font.getAdvanceWidth(' ', FULL)
  })

  const bb = out.getBoundingBox()
  const pad = 1
  const vb = [bb.x1 - pad, bb.y1 - pad, bb.x2 - bb.x1 + pad * 2, bb.y2 - bb.y1 + pad * 2]
    .map(n => +n.toFixed(2))
  const viewBox = vb.join(' ')
  const aspect = +(vb[2] / vb[3]).toFixed(4)
  const d = out.toPathData(1)

  const ts = `// AUTO-GENERATED by scripts/gen-og-wordmark.cjs — do not edit by hand.
// "${TEXT}" outlined in Crimson Pro 600 with small-caps geometry (full-size
// leading capital + scaled small caps, baselines aligned in the path itself).
// Rendered as a vector <path> by the OG image templates so Satori does not need
// font-variant/baseline support. Regenerate: pnpm gen:og-wordmark
export const WORDMARK_VIEWBOX = '${viewBox}'
export const WORDMARK_ASPECT = ${aspect} // width / height
export const WORDMARK_PATH = '${d}'
`
  fs.writeFileSync(OUT, ts)
  console.log(`wrote ${path.relative(process.cwd(), OUT)} — viewBox="${viewBox}" aspect=${aspect}`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
